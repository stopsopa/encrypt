// Builds the single-file libraries:
//   dist/ssenc.node.ts     dist/ssenc.node.js
//   dist/ssenc.browser.ts  dist/ssenc.browser.js
//   dist/cli.ts            dist/cli.js
// The .ts files are plain concatenations of src/ modules (imports between modules removed,
// one explicit export list at the end); the .js files are those same files with the types
// stripped by the TypeScript compiler.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = (f) => readFileSync(join(root, "src", f), "utf8");
const MODULES = ["01-util.ts", "02-blake2b.ts", "03-argon2id.ts", "04-prim.ts", "05-format.ts",
  "06-ssh.ts", "07-sshagent.TARGET.ts", "08-core.ts", "09-exports.ts"];

function bundle(target) {
  let out = `// ssenc - password / ssh-agent encryption to diff-friendly ASCII text.
// Single-file ES module for ${target === "node" ? "Node.js >= 20 (also Deno, Bun)" : "browsers and web workers"}.
// GENERATED by typescript/compile.sh from typescript/src/ - do not edit.
// Format specification: SPEC.md
/* eslint-disable */

const BUILD: string = "${target}";

`;
  for (const name of MODULES) {
    const file = name.replace("TARGET", target);
    const isExports = name === "09-exports.ts";
    for (const line of src(file).split("\n")) {
      if (/^import (type )?\{[^}]*\} from "\.\/[^"]+";$/.test(line)) continue;
      if (/^import /.test(line)) throw new Error(`${file}: only single-line relative named imports are supported: ${line}`);
      out += (isExports ? line : line.replace(/^export (?=(async )?(function|const|class|type) )/, "")) + "\n";
    }
  }
  return out;
}

function transpile(code, fileName) {
  const res = ts.transpileModule(code, {
    fileName,
    reportDiagnostics: true,
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, verbatimModuleSyntax: true, newLine: ts.NewLineKind.LineFeed },
  });
  if (res.diagnostics?.length) throw new Error(ts.formatDiagnostics(res.diagnostics, { getCanonicalFileName: (f) => f, getCurrentDirectory: () => root, getNewLine: () => "\n" }));
  return res.outputText;
}

mkdirSync(join(root, "dist"), { recursive: true });
for (const target of ["node", "browser"]) {
  const code = bundle(target);
  if (target === "browser" && /node:|process\./.test(code)) throw new Error("browser build references Node.js APIs");
  writeFileSync(join(root, "dist", `ssenc.${target}.ts`), code);
  writeFileSync(join(root, "dist", `ssenc.${target}.js`), transpile(code, `ssenc.${target}.ts`));
}
const cli = src("cli.ts");
writeFileSync(join(root, "dist", "cli.ts"), cli);
writeFileSync(join(root, "dist", "cli.js"), transpile(cli.replaceAll('"./ssenc.node.ts"', '"./ssenc.node.js"'), "cli.ts"));
console.log("built dist/ssenc.{node,browser}.{ts,js} and dist/cli.{ts,js}");
